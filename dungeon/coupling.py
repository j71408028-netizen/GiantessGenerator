def normalize_coupling_level(value, default: str = DEFAULT_COUPLING_LEVEL) -> str:
    """把任意来源的值归一化为合法的耦合等级；无法识别时返回 default。"""
    text = str(value or "").strip().lower()
    if text in COUPLING_LEVELS:
        return text
    # 兼容历史配置里可能出现的中文/标签写法
    for level, label in COUPLING_LEVEL_LABELS.items():
        if text == label.lower():
            return level
    return default


def coupling_label(level: str) -> str:
    """返回等级的显示名（Velum / Solea / Bulla）。"""
    return COUPLING_LEVEL_LABELS.get(normalize_coupling_level(level),
                                     COUPLING_LEVEL_LABELS[DEFAULT_COUPLING_LEVEL])


def coupling_initial_prompt(level: str) -> str:
    """返回该等级的初始提示（编辑器直接读取展示，见本模块各档 initial_prompt）。"""
    return coupling_prompts(level).get("initial_prompt", "")


def coupling_prompts(level: str) -> dict:
    """返回该等级的硬编码提示词包；未知等级回退到 Velum。"""
    return COUPLING_PROMPTS.get(normalize_coupling_level(level),
                                COUPLING_PROMPTS[DEFAULT_COUPLING_LEVEL])


def section_instruction(level: str, text_type_value: str, fallback: str = "") -> str:
    """返回该等级下某段落类型的描写指令，未定义时回退到 fallback。"""
    return coupling_prompts(level).get("sections", {}).get(
        str(text_type_value or "").lower(), fallback)
